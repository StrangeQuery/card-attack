"""The "Demo footage" section of CREDITS.md: where the clip and title screen of each of the 8 demos we may show
(cleared by the licence audit, callouts_final.json) came from, one line each in the callouts' order (the giant screen's
montage order), with the audit's licence note, from the gathering's records in the source files' folder
($CARD_ATTACK_WORK, not in this repository: demos/index.json, <slug>/clip.json, demozoo.json, logo_source.json) and demo_footage_audit.json. The other 55 callouts
are parodies with stand-in effects: no footage. Rewrites the section in place (or adds it after "## Demos").

    python segments/stadium/data/make_credits.py
"""
import json
import os
import sys


def _work(*parts):
    """A path in the source files' folder (models, footage, caches; not in this repository), named by CARD_ATTACK_WORK."""
    w = os.environ.get("CARD_ATTACK_WORK")
    if not w:
        sys.exit("set CARD_ATTACK_WORK to the folder holding the source files (they are not in this repository)")
    return os.path.join(os.path.expanduser(w), *parts)


WORK = _work("")
DEMOS = WORK + "demos/"
CALLOUTS = WORK + "callouts_final.json"
AUDIT = WORK + "demo_footage_audit.json"
CREDITS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../../CREDITS.md")
HEAD = "## Demo footage"


def callouts():
    """(title, group, platform and year, slug) of the clips, in the list's order."""
    return [(e["title"], e["group"], e["platform_year"], e["slug"]) for e in json.load(open(CALLOUTS))["callouts"]
            if e["kind"] == "clip"]


def load(path):
    return json.load(open(path)) if os.path.exists(path) else {}


def line(title, group, plat, e):
    d = DEMOS + e["slug"] + "/"
    clip = load(d + "clip.json")
    zoo = load(d + "demozoo.json")
    logo = load(d + "logo_source.json") or e.get("logo") or {}
    audit = {a["slug"]: a for a in load(AUDIT).get("demos", [])}.get(e["slug"], {})
    s = f"- **{title}**, {group} ({plat})"
    if clip:
        s += (f"; clip: \"{clip['video_title']}\", {clip['channel']}, <{clip['video_url']}>, "
              f"{clip['start_s']:g}–{clip['end_s']:g} s")
    page = zoo.get("demozoo_url") or e.get("demozoo")
    if page:
        s += f"; Demozoo: <{page}>"
    if logo.get("kind") == "demozoo screenshot" and logo.get("url"):
        s += f"; title screen (the shirts): <{logo['url']}>"
    elif logo.get("kind"):
        s += "; title screen: a frame of the clip"
    if audit.get("demo_licence"):
        s += f"; licence: {audit['demo_licence']}"
    return s


def main():
    idx = {e["slug"]: e for e in json.load(open(DEMOS + "index.json"))}
    lines = [HEAD, "",
             "The 8 demos whose clips play on the stadium's screens (cleared by a licence audit, "
             "kept with the source files, not in this repository): captures of the demos (YouTube channels named "
             "below), five seconds of each, scaled to 160x120 at 12 fps, shown as a tribute. The demos are their "
             "groups' work. The other 55 callouts on the screens, banners, flags and shirts are parodies (made-up "
             "titles and groups over effects worked out on CARDIAC): no footage. In the giant screen's montage order. "
             "Generated by `segments/stadium/data/make_credits.py`.", ""]
    missing = []
    for title, group, plat, slug in callouts():
        e = idx.get(slug)
        if e is None:
            missing.append(title)
            lines.append(f"- **{title}**, {group} ({plat}): no footage (a stand-in effect)")
            continue
        lines.append(line(title, group, plat, e))
    text = open(CREDITS).read()
    sec = "\n".join(lines) + "\n"
    if HEAD in text:
        a = text.index(HEAD)
        b = text.find("\n## ", a + len(HEAD))
        text = text[:a] + sec + (text[b:] if b >= 0 else "")
    else:
        a = text.index("## Demos")
        b = text.find("\n## ", a + 8)
        text = text[:b + 1] + "\n" + sec + text[b:] if b >= 0 else text + "\n" + sec
    open(CREDITS, "w").write(text)
    print(f"{len(lines) - 4} demos{'; no footage: ' + ', '.join(missing) if missing else ''}")


if __name__ == "__main__":
    main()
